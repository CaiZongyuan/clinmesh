it('retains the departed bed until one CAS clear succeeds when the billing module is absent', async () => {
  const store = createNodeSqliteStore({ dbPath: ':memory:' });
  try {
    const modules = [createInpatientModule()];
    const settings = { ...teachingGate, loadSigningSecret: () => store.visitorSigningSecret() };
    const service = createWorkspaceApp(store, settings, modules);
    const app = createApp('node', settings, (request, credential, entering) => service.fetch(request, { credential, entering }), modules);
    const ward = await wardClient(async (path, init) => app.request(path, init));
    const encounter = await ward.admit('赵德明');
    await ward.role('ward-nurse'); await ward.send('ward.bed.assign', encounter, 1, { bed: 'heart-01' });
    await ward.role('cardiologist');
    await ward.send('ward.diagnose', encounter, 2, { diagnoses: [{ codeSystem: 'urn:clinmesh:reference:nhsa-diagnosis', code: 'I25.103', ordinal: 1, primary: true, poa: 'Y' }] });
    const catalog = z.array(z.object({ id: z.string(), code: z.string() })).parse((await ward.get('/api/his/ward')).items);
    await expect(ward.send('ward.order.sign', encounter, 3, { itemId: catalog.find(row => row.code === 'atorvastatin')!.id, duration: 'temporary', frequency: 'ONCE', dose: 10, route: 'PO' })).rejects.toThrow('WARD_PHARMACY_UNAVAILABLE');
    await ward.send('ward.discharge.issue', encounter, 3);
    await ward.send('ward.discharge.recall', encounter, 4, { reason: 'Recheck before leaving ward' });
    await ward.send('ward.discharge.issue', encounter, 5);
    const visit = encounterViewSchema.parse(await ward.get(`/api/his/encounters/${encounter}`));
    const fields = Object.fromEntries(visit.template.filter(field => field.required).map(field => [field.id, 'Reviewed clinical course']));
    await ward.send('record.draft', encounter, visit.version, { fields, expectedDraftVersion: 0 });
    await ward.send('record.sign', encounter, visit.version + 1);
    const secondary = { codeSystem: 'http://hl7.org/fhir/sid/icd-10', code: 'I10', primary: false };
    await ward.send('diagnosis.draft', encounter, visit.version + 2, { diagnoses: [...visit.diagnoses, secondary] });
    await ward.role('ward-nurse');
    await expect(ward.send('ward.discharge.depart', encounter, 6)).rejects.toThrow('ADMISSION_DIAGNOSIS_REVIEW_REQUIRED');
    await ward.role('cardiologist');
    expect((await ward.get(`/api/his/ward/${encounter}`)).diagnosisDraft).toMatchObject([{ poa: 'Y' }, { code: 'I10', poa: null }]);
    await ward.send('ward.diagnose', encounter, 6, { diagnoses: [{ ...visit.diagnoses[0], ordinal: 1, poa: 'Y' }, { ...secondary, ordinal: 2, poa: 'N' }] });
    await ward.role('ward-nurse'); await ward.send('ward.discharge.depart', encounter, 7);
    expect(await ward.get(`/api/his/ward/${encounter}`)).toMatchObject({ bed: 'heart-01', finance: { canClearBed: true, locked: false } });
    const attempts = await Promise.allSettled([ward.send('ward.discharge.clear', encounter, 8), ward.send('ward.discharge.clear', encounter, 8)]);
    expect(attempts.map(item => item.status).sort()).toEqual(['fulfilled', 'rejected']);
    expect(await ward.get(`/api/his/ward/${encounter}`)).toMatchObject({ status: 'cleared', bed: null });
    await ward.role('cardiologist');
    const ready = encounterViewSchema.parse(await ward.get(`/api/his/encounters/${encounter}`));
    expect(ready.completion.ready).toBe(true);
    await ward.send('encounter.complete', encounter, ready.version);
    const at = { workspaceId: ward.current().workspaceId, epoch: ward.current().epoch };
    await store.withTransaction(tx => {
      const admission = tx.list(at, 'inpatient_admissions', { encounter_id: encounter })[0]!;
      const pageId = v7(), times = { virtual_at: ward.current().virtualTime, recorded_at: new Date().toISOString() };
      tx.insert(at, 'ward_chart_revisions', { id: pageId, admission_id: admission.id, revision: 1, previous_revision_id: null, front_page: { summary: 'Historical front page', disposition: 'Home', followUp: 'Clinic' }, submitted_by: 'cardiologist', ...times });
      tx.insert(at, 'ward_coding_reviews', { id: v7(), revision_id: pageId, reviewed_by: 'records-coder', coding: { note: 'Historical review', diagnoses: [{ ...secondary, ordinal: 2, poa: 'Y' }] }, ...times });
    });
    await ward.role('records-coder');
    expect(await ward.get(`/api/his/ward/${encounter}`)).toMatchObject({ chart: { state: 'resubmit-required', revisions: [{ fields: { summary: 'Historical front page' } }] } });
    await expect(ward.send('ward.chart.archive', encounter, 9, { revision: 1 })).rejects.toThrow('FRONT_PAGE_RESUBMISSION_REQUIRED');
    await ward.role('cardiologist');
    await ward.send('ward.chart.submit', encounter, 9, { summary: 'Reviewed both diagnoses', disposition: 'Home', followUp: 'Clinic' });
    await ward.role('records-coder'); await ward.send('ward.chart.review', encounter, 10, { revision: 2, coding: 'POA confirmed' });
    await ward.send('ward.chart.archive', encounter, 11, { revision: 2 });
    expect(await ward.get(`/api/his/ward/${encounter}`)).toMatchObject({ chart: { state: 'archived', archive: { diagnoses: [{ poa: 'Y' }, { code: 'I10', poa: 'N' }] } } });
  } finally { await store.close(); }
});

it('allocates each available material unit once across patients and stops a previous postoperative long order at the next surgery', () => withNodeWorkspace(async origin => {
  const ward = await wardClient((path, init) => fetch(origin + path, init));
  const first = await ward.admit('赵德明'), second = await ward.admit('周秀兰');
  await ward.role('ward-nurse');
  await ward.send('ward.bed.assign', first, 1, { bed: 'heart-01' }); await ward.send('ward.bed.assign', second, 1, { bed: 'heart-02' });
  await ward.role('cardiologist');
  const catalog = z.array(z.object({ id: z.string(), code: z.string() })).parse((await ward.get('/api/his/ward')).items);
  const item = (code: string) => catalog.find(row => row.code === code)!.id;
  const act = async (encounter: string, operation: string, fields = {}) => ward.send(`ward.${operation}`, encounter, z.int().parse((await ward.get(`/api/his/ward/${encounter}`)).version), fields);
  const notice = { procedureId: item('88.5500'), type: 'elective', plannedAt: ward.current().virtualTime, location: 'cath-lab', surgeon: 'cv-staff-01', anesthesia: 'local', reason: 'Review anatomy', preopOrderPolicy: 'stop-on-completion' };
  await act(first, 'diagnose', { diagnoses: [{ codeSystem: 'urn:clinmesh:reference:nhsa-diagnosis', code: 'I25.103', primary: true, ordinal: 1, poa: 'Y' }] });
  const { requestId } = await act(first, 'surgery.request', { ...notice, materials: [{ itemId: item('wire-014'), quantity: 25 }] });
  await expect(act(second, 'surgery.request', { ...notice, materials: [{ itemId: item('wire-014'), quantity: 1 }] })).rejects.toThrow('MATERIAL_INSUFFICIENT_STOCK');
  await act(first, 'surgery.cancel', { requestId, reason: 'Release material for the receiving patient' });
  await act(second, 'surgery.request', { ...notice, materials: [{ itemId: item('wire-014'), quantity: 25 }] });
  const prepare = async () => {
    const { requestId } = await act(first, 'surgery.request', notice);
    await act(first, 'surgery.consent', { requestId, diagnosisRevision: 1, signer: 'Patient', risks: 'Reviewed risks' });
    await ward.role('ward-nurse'); await act(first, 'surgery.check', { requestId, checklist: 'Confirmed patient and procedure' }); await ward.role('cardiologist');
    return requestId;
  };
  const surgery = await prepare();
  const { executionId } = await act(first, 'surgery.execute', { requestId: surgery });
  const { orderId } = await act(first, 'order.sign', { itemId: item('atorvastatin'), duration: 'long', frequency: 'QD', dose: 10, route: 'PO', surgeryExecutionId: executionId });
  const subsequent = await prepare();
  await act(first, 'surgery.start', { requestId: subsequent });
  const preview = await act(first, 'surgery.preview-completion', { requestId: subsequent }); expect(preview.autoStop).toEqual([orderId]);
  await act(first, 'surgery.complete', { requestId: subsequent, fingerprint: preview.fingerprint });
  expect((await ward.get(`/api/his/ward/${first}`)).orders).toMatchObject([{ id: orderId, status: 'stop-requested' }]);
}, false, { CLINMESH_PORT: '51963' }), 30_000);
