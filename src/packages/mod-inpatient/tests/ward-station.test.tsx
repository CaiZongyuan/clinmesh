it('plans a material on a new PCI notice and completes the reviewed one-unit use without a deviation note', () => withNodeWorkspace(async origin => {
  const transport = globalThis.fetch, human = userEvent.setup();
  const ward = await wardClient((path, init) => transport(origin + path, init));
  const encounter = await ward.admit('赵德明');
  await ward.role('ward-nurse'); await ward.send('ward.bed.assign', encounter, 1, { bed: 'heart-01' });
  await ward.role('cardiologist');
  await ward.send('ward.diagnose', encounter, 2, { diagnoses: [{ codeSystem: 'urn:clinmesh:reference:nhsa-diagnosis', code: 'I25.103', primary: true, ordinal: 1, poa: 'Y' }] });
  vi.stubGlobal('matchMedia', () => Object.assign(new EventTarget(), { matches: true }));
  vi.stubGlobal('fetch', (path: string, init?: RequestInit) => transport(origin + path, { ...init, headers: { ...init?.headers, cookie: ward.cookie } }));
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  render(<QueryClientProvider client={client}><ThemeFontProvider><App/></ThemeFontProvider></QueryClientProvider>);
  const agent = createClinMeshUiAgent();
  const pick = async (ref: string, option: string) => { await waitFor(async () => expect((await agent.act({ steps: [{ ref, action: 'setValue', args: [option] }] })).ok).toBe(true)); };
  await screen.findByRole('combobox', { name: '工作台' }); await pick('工作台', '住院工作台');
  await screen.findByRole('tab', { name: '手术' }); await pick('住院阶段', '手术');
  await screen.findByRole('combobox', { name: '计划术式' }); await pick('计划术式', '药物洗脱冠状动脉支架置入');
  await pick('计划耗材', '0.014 英寸导丝');
  await human.click(screen.getByRole('button', { name: '加入计划耗材' }));
  await human.type(screen.getByRole('textbox', { name: '手术指征' }), '已核实介入指征');
  await human.click(screen.getByRole('button', { name: '签发手术申请' }));
  const read = () => ward.get(`/api/his/ward/${encounter}`);
  const schema = z.array(z.object({ id: z.string(), stages: z.array(z.object({ supplies: z.array(z.object({ itemId: z.string(), planned: z.int() })) })) }));
  await waitFor(async () => expect(schema.parse((await read()).surgeries)[0]?.stages[0]?.supplies[0]?.planned).toBe(1));
  const [request] = schema.parse((await read()).surgeries), requestId = request!.id, itemId = request!.stages[0]!.supplies[0]!.itemId;
  await ward.send('ward.surgery.consent', encounter, 4, { requestId, diagnosisRevision: 1, signer: 'Patient', risks: 'Reviewed access and intervention risks' });
  await ward.role('ward-nurse'); await ward.send('ward.surgery.check', encounter, 5, { requestId, checklist: 'Identity, procedure and access checked' });
  await ward.role('cardiologist');
  await expect(ward.send('ward.surgery.execute', encounter, 6, { requestId, materials: [{ itemId, quantity: 2 }] })).rejects.toThrow('SURGERY_NOTE_REQUIRED');
  await ward.send('ward.surgery.execute', encounter, 6, { requestId, materials: [{ itemId, quantity: 1 }] });
  expect((await read()).surgeries).toMatchObject([{ status: 'completed', stages: [{ supplies: [{ planned: 1, actual: 1 }] }] }]);
  cleanup(); client.clear();
}, false, { CLINMESH_PORT: '51964' }), 30_000);

it('dispenses two selected tasks for one admission and lets the nurse check dose, route and each serum request', () => withNodeWorkspace(async origin => {
  const transport = globalThis.fetch;
  const ward = await wardClient((path, init) => transport(origin + path, init));
  const encounter = await ward.admit('赵德明');
  await ward.role('ward-nurse'); await ward.send('ward.bed.assign', encounter, 1, { bed: 'heart-01' });
  await ward.role('cardiologist'); await ward.send('ward.diagnose', encounter, 2, { diagnoses: [{ codeSystem: 'http://hl7.org/fhir/sid/icd-10', code: 'I21.4', primary: true, ordinal: 1, poa: 'Y' }] });
  const path = `/api/his/encounters/${encounter}`, visit = encounterViewSchema.parse(await ward.get(path));
  await ward.send('record.draft', encounter, visit.version, { expectedDraftVersion: 0, fields: Object.fromEntries(visit.template.filter(field => field.required).map(field => [field.id, `Reviewed ${field.id}`])) });
  await ward.send('record.sign', encounter, visit.version + 1);
  const items = z.array(z.object({ id: z.string(), code: z.string() })).parse((await ward.get('/api/his/ward')).items);
  const drug = (code: string) => items.find(row => row.code === code)!.id;
  const first = await ward.send('ward.order.sign', encounter, 3, { itemId: drug('atorvastatin'), dose: 10, route: 'PO', duration: 'temporary', frequency: 'ONCE' });
  const second = await ward.send('ward.order.sign', encounter, 4, { itemId: drug('aspirin'), dose: 100, route: 'PO', duration: 'temporary', frequency: 'ONCE' });
  const lab = () => ward.get(`${path}/lab`).then(value => labViewSchema.parse(value));
  await ward.send('lab.save-draft', encounter, 0, { serviceIds: [drug('renal'), drug('potassium')] }); await ward.send('lab.issue', encounter, 1, { items: (await lab()).draft.items });
  await ward.role('ward-nurse'); await ward.send('ward.order.verify', encounter, 5, { orderIds: [first.orderId, second.orderId] });
  await ward.role('ward-pharmacist');
  vi.stubGlobal('matchMedia', () => Object.assign(new EventTarget(), { matches: true }));
  vi.stubGlobal('fetch', (address: string, init?: RequestInit) => transport(origin + address, { ...init, headers: { ...init?.headers, cookie: ward.cookie } }));
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const human = userEvent.setup();
  render(<QueryClientProvider client={client}><ThemeFontProvider><App/></ThemeFontProvider></QueryClientProvider>);
  const agent = createClinMeshUiAgent();
  const select = async (ref: string, value: string) => { expect((await agent.act({ steps: [{ ref, action: 'setValue', args: [value] }] })).ok).toBe(true); };
  await screen.findByRole('combobox', { name: '工作台' }); await select('工作台', '住院工作台');
  await screen.findByRole('tab', { name: '诊断医嘱' }); await select('住院阶段', '诊断医嘱');
  const selections = await screen.findAllByRole('checkbox', { name: /勾选发药/ }); expect(selections).toHaveLength(2);
  for (const checkbox of selections) await human.click(checkbox);
  await human.click(await screen.findByRole('button', { name: '集中发放已选任务 (2)' }));
  await waitFor(() => expect(screen.queryByRole('checkbox', { name: /勾选发药/ })).toBeNull());
  expect((await agent.act({ steps: [{ ref: '岗位 · 病区药师', action: 'press', args: ['病房护士'] }] })).ok).toBe(true);
  await screen.findByRole('button', { name: '岗位 · 病房护士' }); await screen.findByRole('tab', { name: '诊断医嘱' }); await select('住院阶段', '诊断医嘱');
  expect((await screen.findByRole('button', { name: /核实给药.*10 mg · PO/ })).getAttribute('data-agent-confirm')).toContain('赵德明');
  await select('住院阶段', '检查检验'); await human.click(await screen.findByRole('checkbox', { name: /血清钾/ }));
  await human.click(await screen.findByRole('button', { name: /送检已核实项目 \(1\)/ }));
  await waitFor(async () => expect((await lab()).orders.map(order => order.status).sort()).toEqual(['accepted', 'issued']));
  cleanup(); client.clear();
}, false, { CLINMESH_PORT: '51964' }), 40_000);
