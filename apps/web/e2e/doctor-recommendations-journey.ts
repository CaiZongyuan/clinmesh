import { expect, type Page } from '@playwright/test'
import type { DoctorCaseDetail } from '@clinmesh/contracts/his'

export async function runRecommendationJourney({ page, read }: { page: Page; read: () => Promise<DoctorCaseDetail> }) {
  await page.getByRole('tab', { name: '诊断', exact: true }).click()
  const diagnosis = page.getByRole('region', { name: '诊断建议', exact: true })
  const adoptDiagnosis = diagnosis.getByRole('button', { name: /^采纳 / })
  await expect(adoptDiagnosis).toBeEnabled()
  await diagnosis.getByText('查看依据', { exact: true }).click()
  await expect(diagnosis.getByRole('link', { name: /WS\/T 872/ })).toHaveAttribute('href', /^https:\/\/www\.nhc\.gov\.cn\//)
  expect((await read()).diagnosis?.confirmation).toBeUndefined()
  await adoptDiagnosis.click()
  const diagnosisDetail = page.getByRole('region', { name: '诊断详情', exact: true })
  await expect(diagnosisDetail.getByLabel('诊断备注', { exact: true })).toBeVisible()
  await expect.poll(async () => (await read()).diagnosis?.draft?.entries.length).toBe(1)
  expect((await read()).diagnosis?.confirmation).toBeUndefined()
  await diagnosisDetail.getByLabel('诊断备注', { exact: true }).fill('合成医生核对后手改，刷新建议须保留。')
  await expect(diagnosis.getByRole('button', { name: '刷新建议', exact: true })).toBeEnabled()
  await diagnosis.getByRole('button', { name: '刷新建议', exact: true }).click()
  await expect(diagnosis.getByRole('button', { name: '刷新建议', exact: true })).toBeEnabled()
  await expect(diagnosisDetail.getByLabel('诊断备注', { exact: true })).toHaveValue('合成医生核对后手改，刷新建议须保留。')
  await page.getByRole('button', { name: '确认诊断', exact: true }).click()
  await page.getByRole('alertdialog', { name: '确认诊断版本', exact: true }).getByRole('button', { name: '确认诊断版本', exact: true }).click()
  await expect.poll(async () => (await read()).diagnosis?.confirmation?.entries[0]?.code).toBe('I10')

  await page.getByRole('tab', { name: '处方', exact: true }).click()
  const prescription = page.getByRole('region', { name: '处方建议', exact: true })
  await expect(prescription.getByRole('button', { name: /^采纳 / })).toBeEnabled()
  await expect(prescription.getByText('待医生补充', { exact: true })).toHaveCount(2)
  await prescription.getByText('查看依据', { exact: true }).click()
  await expect(prescription.getByRole('link', { name: /络活喜/ })).toHaveAttribute('href', /^https:\/\/www\.viatris\.cn\//)
  expect((await read()).medicationConclusion?.prescription).toBeUndefined()
  await prescription.getByRole('button', { name: /^采纳 / }).click()
  const medication = page.getByRole('region', { name: '药品详情', exact: true })
  await expect(medication.getByRole('combobox', { name: '剂量', exact: true })).toContainText('5 mg')
  await expect(medication.getByRole('combobox', { name: '频次', exact: true })).toContainText('QD')
  await expect(medication.getByRole('combobox', { name: '疗程', exact: true })).toContainText('待医生补充')
  await expect(medication.getByRole('combobox', { name: '数量', exact: true })).toContainText('待医生补充')
  await expect(page.getByRole('button', { name: '正式开具处方', exact: true })).toHaveCount(0)
  expect((await read()).medicationConclusion?.draft).toBeUndefined()
  await medication.getByRole('combobox', { name: '疗程', exact: true }).click()
  await page.getByRole('option', { name: '30 天', exact: true }).click()
  await medication.getByRole('combobox', { name: '数量', exact: true }).click()
  await page.getByRole('option', { name: '30', exact: true }).click()
  await expect.poll(async () => (await read()).medicationConclusion?.draft?.items[0]?.quantity).toBe(30)
  expect((await read()).medicationConclusion?.prescription).toBeUndefined()
  await page.getByRole('button', { name: '正式开具处方', exact: true }).click()
  await page.getByRole('alertdialog', { name: '确认正式开具处方', exact: true }).getByRole('button', { name: '确认开具', exact: true }).click()
  await expect.poll(async () => (await read()).medicationConclusion?.prescription?.items[0]?.catalogItemId).toBe('medication-amlodipine')

  await page.getByRole('tab', { name: '检验检查', exact: true }).click()
  const laboratory = page.getByRole('region', { name: '检验建议', exact: true })
  await expect(laboratory.getByRole('button', { name: /^采纳 / })).toBeEnabled()
  expect((await read()).laboratoryRequests?.requests ?? []).toEqual([])
  await laboratory.getByRole('button', { name: /^采纳 / }).click()
  const request = page.getByRole('region', { name: '检验申请', exact: true })
  await expect(request.getByText('合成白细胞计数', { exact: true }).first()).toBeVisible()
  expect((await read()).laboratoryRequests?.requests ?? []).toEqual([])
  await page.getByRole('button', { name: '开具检验申请', exact: true }).click()
  await expect.poll(async () => (await read()).laboratoryRequests?.requests.length).toBe(1)
  return { diagnosisConfirmed: true, prescriptionIssued: true, laboratoryIssued: true, missingPrescriptionFieldsPreserved: true }
}
